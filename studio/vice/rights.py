def load():
    if not REGISTRY.exists():
        save(SEED)
    return json.loads(REGISTRY.read_text())


def save(records):
    REGISTRY.parent.mkdir(parents=True, exist_ok=True)
    REGISTRY.write_text(json.dumps(records, indent=1, ensure_ascii=False) + "\n")


def sync(con=None):
    con = con or db.connect()
    recs = load()
    con.execute("DELETE FROM rights")
    for r in recs:
        con.execute("INSERT INTO rights VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
                    (r["id"], r["asset_class"], json.dumps(r["match"]), r["owner"], r["permission"], r["license_url"],
                     r["commercial_use"], r["creator_restrictions"], r["music_rights"], r["campaign"], r["attribution"],
                     r["expires"], r["content_id_risk"], json.dumps(r["platforms_allowed"]),
                     json.dumps(r["destinations_allowed"]), r["status"], r["notes"], db.now()))
    con.commit()
    return len(recs)


def _norm(asset):
    s = str(asset)
    p = Path(s)
    if p.is_absolute():
        try:
            s = str(p.resolve().relative_to(ROOT))
        except ValueError:
            pass
    if s.startswith("../"):  # episode JSON paths are relative to episodes/
        s = s[3:]
    return s


def find(asset, records=None):
    s = _norm(asset)
    for r in records or load():
        if any(fnmatch.fnmatch(s, m) for m in r["match"]):
            return r
    return None


def check(asset, destination, ai_voice=False, branding=False, platform="YouTube", today=None, log=True, registered=True):
    """Rights gate for one asset. Returns {"ok", "record", "reasons", "conditions"}; ok=False blocks publishing.
    A file registered with `add-source` is judged by its own record (sources.strict_check); everything else by the
    class registry. Every decision is appended to the rights_audit table."""
    if registered and not str(asset).startswith(("campaign:", "voice:", "music:", "http")):
        from . import sources
        con = sources.connect()
        src = sources.by_path(con, db.ROOT / _norm(asset) if not Path(str(asset)).is_absolute() else asset)
        if src:
            ok, reasons = sources.strict_check(src, destination, ai_voice=ai_voice, branding=branding, con=con if log else None)
            return {"ok": ok, "asset": _norm(asset), "record": f"source:{src['id']} ({src['rights_status']})",
                    "reasons": reasons, "conditions": [src["notes"]] if src["notes"] else []}
    res = _class_check(asset, destination, ai_voice, branding, platform, today)
    if log:
        from . import sources
        sources.audit(sources.connect(), res["asset"], destination, res["ok"], res["reasons"], "rights.check")
    return res


def _class_check(asset, destination, ai_voice=False, branding=False, platform="YouTube", today=None):
    rec = find(asset)
    reasons, conditions = [], []
    if not rec:
        return {"ok": False, "asset": _norm(asset), "record": None,
                "reasons": ["no rights record matches this source: blocked by default (add a record with real permission)"],
                "conditions": []}
    if rec["status"] == "blocked":
        reasons.append(f"rights record '{rec['id']}' is blocked: {rec['notes']}")
    if destination not in rec["destinations_allowed"]:
        reasons.append(f"'{rec['id']}' may not be published on '{destination}' (allowed: {rec['destinations_allowed'] or 'none'})")
    if platform and rec["platforms_allowed"] and platform not in rec["platforms_allowed"]:
        reasons.append(f"platform {platform} not allowed by '{rec['id']}'")
    restr = (rec.get("creator_restrictions") or "").lower()
    if ai_voice and "no ai" in restr:
        reasons.append(f"'{rec['id']}' forbids AI voice/visuals")
    if branding and "no logos" in restr:
        reasons.append(f"'{rec['id']}' forbids logos/branding")
    exp = rec.get("expires")
    if exp and exp[:4].isdigit() and (today or dt.date.today().isoformat()) > exp:
        reasons.append(f"permission expired {exp}")
    if rec["status"] == "conditional":
        conditions.append(rec["creator_restrictions"])
        if rec.get("music_rights", "").startswith("BLOCKED"):
            conditions.append("drop the clip's original audio")
    return {"ok": not reasons, "asset": _norm(asset), "record": rec["id"], "reasons": reasons,
            "conditions": [c for c in conditions if c]}


def check_episode(ep, destination="vice-replay"):
    """Every media file an episode uses, plus the narration voice and music, through the gate."""
    assets = []
    groups = [ep.get(k) or [] for k in ("segments", "short", "news_short", "tips_short")]
    groups += [sh.get("segments") or [] for sh in ep.get("shorts") or []]  # Nov 22: multi-Short episodes and
    for segs in groups:                                                     # pictures inside "shots" were unchecked
        for s in segs:
            if s.get("media"):
                assets.append(s["media"])
            assets += [s[k] for k in ("audio", "audio_es") if s.get(k)]  # ready-made voice files (Everygen)
            assets += [x["media"] for x in s.get("shots") or [] if x.get("media")]
    thumb = (ep.get("thumbnail") or {}).get("image")
    if thumb:
        assets.append(thumb)
    results = [check(a, destination) for a in dict.fromkeys(assets)]
    if any(not (s.get("audio") or s.get("audio_es")) for segs in groups for s in segs):
        results.append(check("voice:kokoro", destination))
    if ep.get("music", "theme") not in ("none", None):
        results.append(check("assets/music/vice-replay-theme.wav", destination))
    return {"ok": all(r["ok"] for r in results), "checks": results}
